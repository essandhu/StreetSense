# --- Append-only enforcement at the role level ----------------------------
class TestAppendOnlyAtRoleLevel:
    @pytest.mark.parametrize("table", ["scoring_runs", "segment_scores"])
    def test_update_is_revoked_for_app_role(
        self, app_conn: psycopg.Connection[Any], table: str
    ) -> None:
        with app_conn.cursor() as cur, pytest.raises(pg_errors.InsufficientPrivilege):
            cur.execute(f"UPDATE {table} SET id = id WHERE FALSE")
        app_conn.rollback()

    @pytest.mark.parametrize("table", ["scoring_runs", "segment_scores"])
    def test_delete_is_revoked_for_app_role(
        self, app_conn: psycopg.Connection[Any], table: str
    ) -> None:
        with app_conn.cursor() as cur, pytest.raises(pg_errors.InsufficientPrivilege):
            cur.execute(f"DELETE FROM {table} WHERE FALSE")
        app_conn.rollback()


# --- UUIDs not SERIAL across the board ------------------------------------
class TestUUIDPrimaryKeys:
    @pytest.mark.parametrize("table", ["road_segments", "scoring_runs", "segment_scores"])
    def test_primary_key_is_uuid(self, owner_conn: psycopg.Connection[Any], table: str) -> None:
        pk_col = _primary_key_column(owner_conn, table)
        cols = _column_info(owner_conn, table)
        data_type, _, default = cols[pk_col]
        assert data_type == "uuid", f"{table}.{pk_col} is {data_type}, expected uuid"
        assert default is not None
        assert "gen_random_uuid" in default
        assert "nextval" not in default

    @pytest.mark.parametrize("table", ["road_segments", "scoring_runs", "segment_scores"])
    def test_no_sequences_on_table(self, owner_conn: psycopg.Connection[Any], table: str) -> None:
        with owner_conn.cursor() as cur:
            cur.execute(
                """
                SELECT s.relname
                FROM pg_class s
                JOIN pg_depend d ON d.objid = s.oid AND d.deptype = 'a'
                JOIN pg_class t ON t.oid = d.refobjid
                WHERE s.relkind = 'S' AND t.relname = %s
                """,
                (table,),
            )
            seqs = [row[0] for row in cur.fetchall()]
        assert seqs == [], f"{table} owns sequences (SERIAL?): {seqs}"


# --- Sanity: UUIDs round-trip ---------------------------------------------
def test_uuid_round_trip(owner_conn: psycopg.Connection[Any]) -> None:
    with owner_conn.cursor() as cur:
        cur.execute("SELECT gen_random_uuid()")
        row = cur.fetchone()
        assert row is not None
        uid = row[0]
        assert isinstance(uid, UUID)
